using EasyVan.Data;
using EasyVan.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Xunit;

namespace EasyVan.Tests;

public class PostgreSqlCompatibilityTests
{
    [Fact]
    public void PostgreSqlModel_CriaIndiceParcialDeVinculoAtivoComPredicadoPostgres()
    {
        var options = new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseNpgsql("Host=localhost;Database=easyvan_model_test;Username=test;Password=test")
            .Options;

        using var db = new ApplicationDbContext(options);
        var schema = db.Database.GenerateCreateScript();
        var migrations = db.GetService<IMigrator>().GenerateScript();

        Assert.Contains("IX_VinculosAluno_AlunoSentidoAtivo", schema, StringComparison.Ordinal);
        Assert.Contains("WHERE \"Ativo\" = TRUE", schema, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("WHERE \"Ativo\" = TRUE", migrations, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("WHERE \"Ativo\" = 1", migrations, StringComparison.OrdinalIgnoreCase);
    }

    private static DbContextOptions<ApplicationDbContext>? CreateOptions()
    {
        var connectionString = Environment.GetEnvironmentVariable("EASYVAN_TEST_POSTGRES");
        if (string.IsNullOrWhiteSpace(connectionString)) return null;
        return new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connectionString).Options;
    }

    [Fact]
    public void PostgreSqlModel_UsesNativeTypesAndIdentityColumns()
    {
        var options = CreateOptions();
        if (options is null) return;
        using var db = new ApplicationDbContext(options);
        var script = db.Database.GenerateCreateScript();
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", script, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("AUTOINCREMENT", script, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("COLLATE NOCASE", script, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("boolean", script, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task PostgreSqlDatabase_GeneratesIdsWhenInsertingEntities()
    {
        var options = CreateOptions();
        if (options is null) return;
        await using var db = new ApplicationDbContext(options);
        await db.Database.EnsureDeletedAsync();
        await db.Database.EnsureCreatedAsync();
        var email = $"postgres-{Guid.NewGuid():N}@easyvan.test";
        var user = new Usuarios { Nome = "Teste PostgreSQL", Email = email, RoleManager = "Aluno", PasswordHasher = "hash-de-teste", Tema = "claro" };
        db.Usuarios.Add(user);
        await db.SaveChangesAsync();
        Assert.True(user.Id > 0);
        Assert.Equal(user.Id, await db.Usuarios.Where(x => x.Email == email).Select(x => x.Id).SingleAsync());
        await db.Usuarios.Where(x => x.Email == email).ExecuteDeleteAsync();
    }

    [Fact]
    public void PostgreSqlMigrationScript_DoesNotContainSqliteOnlySyntax()
    {
        var options = CreateOptions();
        if (options is null) return;
        using var db = new ApplicationDbContext(options);
        var script = db.GetService<IMigrator>().GenerateScript();
        Assert.DoesNotContain("AUTOINCREMENT", script, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("COLLATE NOCASE", script, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("Sqlite:Autoincrement", script, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", script, StringComparison.OrdinalIgnoreCase);
    }
}
